export interface BookProgress {
  user_id: string;
  current_page: number;
  day_start_date: string;
  day_start_page: number;
  updated_at: string;
}

export function clampPage(page: number): number {
  return Number.isFinite(page) ? Math.max(0, Math.min(BOOK.totalPages, Math.trunc(page))) : 0;
}

export function bookPercent(page: number): number {
  return Math.round((clampPage(page) / BOOK.totalPages) * 100);
}

export function currentChapter(page: number): BookChapter | undefined {
  return [...BOOK.chapters].reverse().find((chapter) => chapter[3] <= clampPage(page));
}

export function chapterTitle(chapter: BookChapter): string {
  return `${chapter[1] === null ? "" : `${chapter[1]}. `}${chapter[2]}`;
}

export function pagesReadToday(progress: BookProgress | undefined, today: string): number {
  return progress?.day_start_date === today ? Math.max(0, progress.current_page - progress.day_start_page) : 0;
}

export function shouldRemindBookTask(pages: number): boolean {
  return pages >= 10;
}

export function groupBookStats(rows: readonly BookProgress[]) {
  return { readers: rows.length, percent: rows.length ? Math.round(rows.reduce((sum, row) => sum + clampPage(row.current_page), 0) / (rows.length * BOOK.totalPages) * 100) : 0 };
}

export function rankReaders<T extends { id: string; display_name: string }>(profiles: readonly T[], rows: readonly BookProgress[]) {
  const byUser = new Map(rows.map((row) => [row.user_id, row]));
  return profiles.map((profile) => ({ ...profile, page: byUser.get(profile.id)?.current_page ?? 0 }))
    .sort((a, b) => b.page - a.page || a.display_name.localeCompare(b.display_name, "ru") || a.id.localeCompare(b.id));
}

