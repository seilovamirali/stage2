export const DAILY_MOTIVATION = DAILY_SPEECHES.map(([first, second]) => `${first} ${second}`);

export function motivationForDate(date: string): string {
  const day = Number(date.slice(8, 10)) || 1;
  return DAILY_MOTIVATION[(day - 1) % DAILY_MOTIVATION.length] ?? DAILY_MOTIVATION[0] ?? "";
}

export function habitsLeftLine(remaining: number): string {
  if (remaining <= 0) return "Все привычки на сегодня закрыты.";
  const mod10 = remaining % 10;
  const mod100 = remaining % 100;
  const word =
    mod10 === 1 && mod100 !== 11 ? "привычка" :
    mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? "привычки" :
    "привычек";
  const verb = word === "привычка" ? "Осталась" : "Осталось";
  const pronoun = remaining === 1 ? "её" : "их";
  return `${verb} ${remaining} ${word} — закрой ${pronoun} до полуночи.`;
}

export function dailySpeech(date: string, remaining: number): string {
  const day = Number(date.slice(8, 10)) || 1;
  const pair = DAILY_SPEECHES[(day - 1) % DAILY_SPEECHES.length] ?? DAILY_SPEECHES[0];
  if (!pair) return habitsLeftLine(remaining);
  if (remaining <= 0) return `${pair[0]} Все привычки на сегодня закрыты.`;
  return `${pair[0]} ${pair[1]} ${habitsLeftLine(remaining)}`;
}
