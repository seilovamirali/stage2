export function vehicleCheer(date: string, pace: number): string {
  const tier = vehicleTier(pace);
  const lines = CHEERS[tier.id];
  const day = Number(date.slice(8, 10)) || 1;
  return lines[(day - 1) % lines.length] ?? lines[0] ?? "";
}
